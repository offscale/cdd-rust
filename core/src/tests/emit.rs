/// # Returns
/// Resulting `Vec<String>` value.
fn serialize_cookie_object(
    name: &str,
    style: &ParamStyle,
    explode: bool,
    map: &serde_json::Map<String, serde_json::Value>,
) -> Vec<String> {
    if map.is_empty() {
        return Vec::new();
    }

    match style {
        ParamStyle::SpaceDelimited => {
            let joined = map
                .iter()
                .flat_map(|(k, v)| [k.clone(), example_to_string(v)])
                .collect::<Vec<_>>()
                .join(" ");
            vec![format!("{}={}", name, joined)]
        }
        ParamStyle::PipeDelimited => {
            let joined = map
                .iter()
                .flat_map(|(k, v)| [k.clone(), example_to_string(v)])
                .collect::<Vec<_>>()
                .join("|");
            vec![format!("{}={}", name, joined)]
        }
        _ => {
            if explode {
                map.iter()
                    .map(|(k, v)| format!("{}={}", k, example_to_string(v)))
                    .collect()
            } else {
                let joined = map
                    .iter()
                    .flat_map(|(k, v)| [k.clone(), example_to_string(v)])
                    .collect::<Vec<_>>()
                    .join(",");
                vec![format!("{}={}", name, joined)]
            }
        }
    }
}

/// Executes `serialize_query_param` (serialize query param).
///
/// # Arguments
/// * `param` - Input `param` parameter.
///
/// # Returns
/// Resulting `Vec<String>` value.
fn serialize_query_param(param: &crate::openapi::parse::RouteParam) -> Vec<String> {
    if let Some(example) = &param.example {
        if example.is_serialized() {
            return vec![example_value_to_string(example)];
        }
    }

    let value = match param.example.as_ref() {
        Some(example) => example.value.clone(),
        None if param.allow_empty_value => serde_json::Value::String(String::new()),
        None => dummy_json_value(&param.ty),
    };
    let style = param.style.clone().unwrap_or(ParamStyle::Form);

    match value {
        serde_json::Value::Array(arr) => serialize_array_param(
            &param.name,
            &style,
            param.explode,
            param.allow_reserved,
            &arr,
        ),
        serde_json::Value::Object(map) => serialize_object_param(
            &param.name,
            &style,
            param.explode,
            param.allow_reserved,
            &map,
        ),
        _ => vec![format!(
            "{}={}",
            encode_name(&param.name),
            encode_value(&example_to_string(&value), param.allow_reserved)
        )],
    }
}

/// Executes `serialize_array_param` (serialize array param).
///
/// # Arguments
/// * `name` - Input `name` parameter.
/// * `style` - Input `style` parameter.
/// * `explode` - Input `explode` parameter.
/// * `allow_reserved` - Input `allow_reserved` parameter.
/// * `items` - Input `items` parameter.
///
/// # Returns
/// Resulting `Vec<String>` value.
fn serialize_array_param(
    name: &str,
    style: &ParamStyle,
    explode: bool,
    allow_reserved: bool,
    items: &[serde_json::Value],
) -> Vec<String> {
    if items.is_empty() {
        return Vec::new();
    }

    match style {
        ParamStyle::SpaceDelimited => {
            let joined = items
                .iter()
                .map(|v| encode_value(&example_to_string(v), allow_reserved))
                .collect::<Vec<_>>()
                .join("%20");
            vec![format!("{}={}", encode_name(name), joined)]
        }
        ParamStyle::PipeDelimited => {
            let joined = items
                .iter()
                .map(|v| encode_value(&example_to_string(v), allow_reserved))
                .collect::<Vec<_>>()
                .join("%7C");
            vec![format!("{}={}", encode_name(name), joined)]
        }
        ParamStyle::Form
        | ParamStyle::DeepObject
        | ParamStyle::Simple
        | ParamStyle::Label
        | ParamStyle::Matrix
        | ParamStyle::Cookie => {
            if explode {
                items
                    .iter()
                    .map(|v| {
                        format!(
                            "{}={}",
                            encode_name(name),
                            encode_value(&example_to_string(v), allow_reserved)
                        )
                    })
                    .collect()
            } else {
                let joined = items
                    .iter()
                    .map(|v| encode_value(&example_to_string(v), allow_reserved))
                    .collect::<Vec<_>>()
                    .join(",");
                vec![format!("{}={}", encode_name(name), joined)]
            }
        }
    }
}

/// Executes `serialize_object_param` (serialize object param).
///
/// # Arguments
/// * `name` - Input `name` parameter.
/// * `style` - Input `style` parameter.
/// * `explode` - Input `explode` parameter.
/// * `allow_reserved` - Input `allow_reserved` parameter.
/// * `map` - Input `map` parameter.
///
/// # Returns
/// Resulting `Vec<String>` value.
fn serialize_object_param(
    name: &str,
    style: &ParamStyle,
    explode: bool,
    allow_reserved: bool,
    map: &serde_json::Map<String, serde_json::Value>,
) -> Vec<String> {
    if map.is_empty() {
        return Vec::new();
    }

    match style {
        ParamStyle::DeepObject => map
            .iter()
            .map(|(k, v)| {
                format!(
                    "{}={}",
                    encode_deep_object_name(name, k),
                    encode_value(&example_to_string(v), allow_reserved)
                )
            })
            .collect(),
        ParamStyle::SpaceDelimited => {
            let joined = map
                .iter()
                .flat_map(|(k, v)| {
                    [
                        encode_value(k, allow_reserved),
                        encode_value(&example_to_string(v), allow_reserved),
                    ]
                })
                .collect::<Vec<_>>()
                .join("%20");
            vec![format!("{}={}", encode_name(name), joined)]
        }
        ParamStyle::PipeDelimited => {
            let joined = map
                .iter()
                .flat_map(|(k, v)| {
                    [
                        encode_value(k, allow_reserved),
                        encode_value(&example_to_string(v), allow_reserved),
                    ]
                })
                .collect::<Vec<_>>()
                .join("%7C");
            vec![format!("{}={}", encode_name(name), joined)]
        }
        ParamStyle::Form
        | ParamStyle::Simple
        | ParamStyle::Label
        | ParamStyle::Matrix
        | ParamStyle::Cookie => {
            if explode {
                map.iter()
                    .map(|(k, v)| {
                        format!(
                            "{}={}",
                            encode_name(k),
                            encode_value(&example_to_string(v), allow_reserved)
                        )
                    })
                    .collect()
            } else {
                let joined = map
                    .iter()
                    .flat_map(|(k, v)| {
                        [
                            encode_value(k, allow_reserved),
                            encode_value(&example_to_string(v), allow_reserved),
                        ]
                    })
                    .collect::<Vec<_>>()
                    .join(",");
                vec![format!("{}={}", encode_name(name), joined)]
            }
        }
    }
}

/// Executes `encode_deep_object_name` (encode deep object name).
///
/// # Arguments
/// * `param_name` - Input `param_name` parameter.
/// * `key` - Input `key` parameter.
///
/// # Returns
/// Resulting `String` value.
fn encode_deep_object_name(param_name: &str, key: &str) -> String {
    let name = encode_name(param_name);
    let key = encode_name(key);
    format!("{}%5B{}%5D", name, key)
}

/// Executes `encode_name` (encode name).
///
/// # Arguments
/// * `name` - Input `name` parameter.
///
/// # Returns
/// Resulting `String` value.
fn encode_name(name: &str) -> String {
    encode_rfc3986(name, false)
}

/// Executes `encode_value` (encode value).
///
/// # Arguments
/// * `value` - Input `value` parameter.
/// * `allow_reserved` - Input `allow_reserved` parameter.
///
/// # Returns
/// Resulting `String` value.
fn encode_value(value: &str, allow_reserved: bool) -> String {
    encode_rfc3986(value, allow_reserved)
}

/// Executes `serialize_form_urlencoded_querystring` (serialize form urlencoded querystring).
///
/// # Arguments
/// * `value` - Input `value` parameter.
///
/// # Returns
/// Resulting `String` value.
fn serialize_form_urlencoded_querystring(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::Object(map) => map
            .iter()
            .map(|(k, v)| {
                format!(
                    "{}={}",
                    encode_form_urlencoded(k),
                    encode_form_urlencoded(&example_to_string(v))
                )
            })
            .collect::<Vec<_>>()
            .join("&"),
        serde_json::Value::String(s) => s.clone(),
        _ => encode_form_urlencoded(&example_to_string(value)),
    }
}

/// Executes `encode_rfc3986` (encode rfc3986).
///
/// # Arguments
/// * `input` - Input `input` parameter.
/// * `allow_reserved` - Input `allow_reserved` parameter.
///
/// # Returns
/// Resulting `String` value.
fn encode_rfc3986(input: &str, allow_reserved: bool) -> String {
    let bytes = input.as_bytes();
    let mut out = String::new();
    let mut idx = 0;

    while idx < bytes.len() {
        let b = bytes[idx];

        if allow_reserved && b == b'%' && idx + 2 < bytes.len() {
            let b1 = bytes[idx + 1];
            let b2 = bytes[idx + 2];
            if is_hex_digit(b1) && is_hex_digit(b2) {
                out.push('%');
                out.push(b1 as char);
                out.push(b2 as char);
                idx += 3;
                continue;
            }
        }

        if is_unreserved(b) || (allow_reserved && is_reserved(b)) {
            out.push(b as char);
        } else {
            out.push_str(&format!("%{:02X}", b));
        }
        idx += 1;
    }

    out
}

/// Executes `is_unreserved` (is unreserved).
///
/// # Arguments
/// * `b` - Input `b` parameter.
///
/// # Returns
/// Resulting `bool` value.
fn is_unreserved(b: u8) -> bool {
    matches!(
        b,
        b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'.' | b'_' | b'~'
    )
}

/// Executes `is_reserved` (is reserved).
///
/// # Arguments
/// * `b` - Input `b` parameter.
///
/// # Returns
/// Resulting `bool` value.
fn is_reserved(b: u8) -> bool {
    matches!(
        b,
        b':' | b'/'
            | b'?'
            | b'#'
            | b'['
            | b']'
            | b'@'
            | b'!'
            | b'$'
            | b'&'
            | b'\''
            | b'('
            | b')'
            | b'*'
            | b'+'
            | b','
            | b';'
            | b'='
    )
}

/// Executes `is_hex_digit` (is hex digit).
///
/// # Arguments
/// * `b` - Input `b` parameter.
///
/// # Returns
/// Resulting `bool` value.
fn is_hex_digit(b: u8) -> bool {
    b.is_ascii_hexdigit()
}

/// Executes `encode_form_urlencoded` (encode form urlencoded).
///
/// # Arguments
/// * `input` - Input `input` parameter.
///
/// # Returns
/// Resulting `String` value.
fn encode_form_urlencoded(input: &str) -> String {
    let bytes = input.as_bytes();
    let mut out = String::new();
    for &b in bytes {
        match b {
            b' ' => out.push('+'),
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'.' | b'_' | b'*' => {
                out.push(b as char)
            }
            _ => out.push_str(&format!("%{:02X}", b)),
        }
    }
    out
}

